// Regenerates public/third-party-licenses.txt: the licence texts of every runtime (production)
// dependency of the frontend, which the production bundle redistributes.
// Run after changing dependencies:  node scripts/generate-licenses.mjs
// Needs `pnpm install` to have run (reads node_modules). Adds no dependencies.
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const rootPkg = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'))
const LICENSE_FILE = /^(licen[sc]e|copying|notice|third_party_notices)(\.|$|-)/i

/** Finds node_modules/<name> by walking up from `fromDir`, like Node's resolver. */
function resolvePkg(name, fromDir) {
  for (let dir = fs.realpathSync(fromDir); ; dir = path.dirname(dir)) {
    const candidate = path.join(dir, 'node_modules', name)
    if (fs.existsSync(path.join(candidate, 'package.json'))) return fs.realpathSync(candidate)
    if (path.dirname(dir) === dir) return null
  }
}

const found = new Map() // dir -> package.json
function visit(name, fromDir, optional) {
  const dir = resolvePkg(name, fromDir)
  if (!dir) {
    if (!optional) console.warn(`not found: ${name} (from ${fromDir})`)
    return
  }
  if (found.has(dir)) return
  const pkg = JSON.parse(fs.readFileSync(path.join(dir, 'package.json'), 'utf8'))
  found.set(dir, pkg)
  for (const dep of Object.keys(pkg.dependencies ?? {})) visit(dep, dir, false)
  for (const dep of Object.keys({ ...pkg.peerDependencies, ...pkg.optionalDependencies })) visit(dep, dir, true)
}
for (const dep of Object.keys(rootPkg.dependencies)) visit(dep, root, false)

const licenseOf = (pkg) =>
  typeof pkg.license === 'string' ? pkg.license : (pkg.license?.type ?? pkg.licenses?.map((l) => l.type).join(' OR ') ?? 'UNKNOWN')

const entries = [...found].map(([dir, pkg]) => {
  const files = [dir, path.join(dir, 'licenses')]
    .filter((d) => fs.existsSync(d))
    .flatMap((d) => fs.readdirSync(d, { withFileTypes: true }).filter((f) => f.isFile() && LICENSE_FILE.test(f.name) || d.endsWith('licenses') && f.isFile()).map((f) => path.join(d, f.name)))
  return { name: pkg.name, version: pkg.version, license: licenseOf(pkg), files, author: typeof pkg.author === 'string' ? pkg.author : pkg.author?.name }
})
entries.sort((a, b) => a.name.localeCompare(b.name))

